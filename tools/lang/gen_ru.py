"""Generates ru_strings.h for SlaverMod: English text of T()/L() -> Russian, as hex-escaped C literals.

    python tools/lang/gen_ru.py ru_strings.h

ru_text.py maps each English text of T()/L() (as written in SlaverMod.cpp, C escapes kept) to Russian.
tools/lang/extract_tl.py lists the texts of SlaverMod.cpp, to find new ones without a translation.
"""
import json, os, sys, string
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ru_text import RU, LINES


def c_lit(text):
    out, prev_hex = [], False
    for ch in text:
        b = ch.encode('utf-8')
        if len(b) > 1:
            out.append(''.join('\\x%02x' % x for x in b))
            prev_hex = True
            continue
        if prev_hex and ch in string.hexdigits:
            out.append('" "')   # a hex escape would swallow the next hex digit
        prev_hex = False
        out.append({'"': '\\"', '\\': '\\\\', '\n': '\\n'}.get(ch, ch))
    return '"' + ''.join(out) + '"'


def main():
    lines = ['// Generated by tools/lang/gen_ru.py from tools/lang/ru_text.py: English text of T()/L() -> Russian.',
             '// Texts missing here stay in English. Hex escapes keep the UTF-8 bytes whatever the compiler code page.',
             'static const char* const RU_TEXT[][2] = {']
    for en_raw, ru in RU.items():
        lines.append('    { "%s", %s },' % (en_raw, c_lit(ru)))
    lines.append('};')
    lines.append('static const char* const RU_LINES[][2] = {')
    for k, v in LINES.items():
        lines.append('    { "%s", %s },' % (k, c_lit(v)))
    lines.append('};')
    open(sys.argv[1], 'w', encoding='ascii', newline='\r\n').write('\n'.join(lines) + '\n')
    print('ok: %d texts, %d speech keys' % (len(RU), len(LINES)))


if __name__ == '__main__':
    main()
